@st.cache_data(show_spinner=False)
def csv(path):
    return pd.read_csv(path, low_memory=False)


@st.cache_data(show_spinner=False)
def parquet(path):
    return pd.read_parquet(path)


@st.cache_data(show_spinner=False)
def transcript_sites(path, transcript_id):
    import pyarrow.dataset as ds

    dataset = ds.dataset(str(path), format="parquet")
    needed = [
        "transcript_id", "transcript_position",
        "mean_score", "std_score",
        "min_score", "max_score",
        "n_detected_runs", "n_total_runs",
    ]
    columns = [c for c in needed if c in dataset.schema.names]

    table = dataset.to_table(
        columns=columns,
        filter=(ds.field("transcript_id") == transcript_id)
    )
    return table.to_pandas()


def require(path):
    if not path.exists():
        st.error(f"Required file missing: {path}")
        st.stop()
    return path


def threshold_tag(t):
    return f"{float(t):.1f}"


def rate(n, d):
    return n / d if d else np.nan


