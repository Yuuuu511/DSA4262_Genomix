def current_pair_summary(base_summary, active_sites):
    result = base_summary[
        ["cell_a", "cell_b", "pair", "n_matched_sites"]
    ].copy()

    if active_sites.empty:
        result["n_selected"] = 0
        result["n_strict"] = 0
    else:
        by_pair = (
            active_sites.groupby("pair")
            .agg(
                n_selected=("transcript_id", "size"),
                n_strict=("replicate_supported", "sum"),
            )
            .reset_index()
        )
        result = result.merge(by_pair, on="pair", how="left")
        result[["n_selected", "n_strict"]] = (
            result[["n_selected", "n_strict"]]
            .fillna(0).astype(int)
        )

    result["selected_fraction"] = (
        result["n_selected"] / result["n_matched_sites"]
    )
    result["strict_support_rate"] = np.where(
        result["n_selected"] > 0,
        result["n_strict"] / result["n_selected"],
        np.nan,
    )
    result["strict_fraction_of_matched"] = (
        result["n_strict"] / result["n_matched_sites"]
    )
    return result


current_summary = current_pair_summary(
    atlas_summary, active_atlas
)


def pair_name(a, b):
    matches = atlas_summary[
        (
            (atlas_summary.cell_a == a)
            & (atlas_summary.cell_b == b)
        )
        |
        (
            (atlas_summary.cell_a == b)
            & (atlas_summary.cell_b == a)
        )
    ]
    return str(matches.iloc[0]["pair"]) if len(matches) else None


def similarity_matrix(df, col):
    mat = pd.DataFrame(
        np.nan, index=cells, columns=cells
    )
    for _, row in df.iterrows():
        a, b = row["cell_a"], row["cell_b"]
        mat.loc[a, b] = row[col]
        mat.loc[b, a] = row[col]
    return mat


def show_heatmap(mat, title):
    arr = mat.to_numpy(dtype=float)
    valid = arr[np.isfinite(arr)]

    if not len(valid):
        st.info("No values available.")
        return

    pad = max(0.01, np.ptp(valid) * 0.08)

    zmin = max(0.0, float(valid.min()) - pad)
    zmax = min(1.0, float(valid.max()) + pad)

    fig = go.Figure(
        go.Heatmap(
            z=arr,
            x=list(mat.columns),
            y=list(mat.index),
            colorscale="Blues",
            zmin=zmin,
            zmax=zmax,
            hoverongaps=False,
            hovertemplate=(
                "%{y} vs %{x}<br>"
                "Value: %{z:.3f}<extra></extra>"
            ),
        )
    )
    for i, a in enumerate(mat.index):
        for j, b in enumerate(mat.columns):
            value = arr[i, j]
            if i != j and np.isfinite(value):
                fig.add_annotation(
                    x=b, y=a,
                    text=f"{value:.3f}",
                    showarrow=False,
                    font=dict(size=10),
                )

    fig.update_layout(
        title=title,
        height=490,
        yaxis=dict(autorange="reversed"),
    )
    plot(fig)


