def pair_name(a, b):
    matches = atlas_summary[
        (
            (atlas_summary.cell_a == a)
            & (atlas_summary.cell_b == b)
        )
        |
        (
            (atlas_summary.cell_a == b)
            & (atlas_summary.cell_b == a)
        )
    ]
    return str(matches.iloc[0]["pair"]) if len(matches) else None


def similarity_matrix(df, col):
    mat = pd.DataFrame(
        np.nan, index=cells, columns=cells
    )
    for _, row in df.iterrows():
        a, b = row["cell_a"], row["cell_b"]
        mat.loc[a, b] = row[col]
        mat.loc[b, a] = row[col]
    return mat


def show_heatmap(mat, title, measure):
    arr = mat.to_numpy(dtype=float)
    valid = arr[np.isfinite(arr)]

    if not len(valid):
        st.info("No results are available for this comparison.")
        return

    pad = max(0.01, np.ptp(valid) * 0.08)

    zmin = max(0.0, float(valid.min()) - pad)
    zmax = min(1.0, float(valid.max()) + pad)

    fig = go.Figure(
        go.Heatmap(
            z=arr,
            x=list(mat.columns),
            y=list(mat.index),
            colorscale="Blues",
            colorbar=dict(title=dict(text=measure, side="bottom")),
            zmin=zmin,
            zmax=zmax,
            hoverongaps=False,
            hovertemplate=(
                "%{y} vs %{x}<br>"
                "Value: %{z:.3f}<extra></extra>"
            ),
        )
    )
    for i, a in enumerate(mat.index):
        for j, b in enumerate(mat.columns):
            value = arr[i, j]
            if i != j and np.isfinite(value):
                rgb = np.array([int(c) for c in re.findall(r"\d+", px.colors.sample_colorscale("Blues", [(value-zmin)/(zmax-zmin)])[0])]) / 255
                linear = np.where(rgb <= .04045, rgb/12.92, ((rgb+.055)/1.055)**2.4)
                luminance = linear @ np.array([.2126, .7152, .0722])
                fig.add_annotation(
                    x=b, y=a,
                    text=f"{value:.3f}",
                    showarrow=False,
                    font=dict(size=12, color="white" if luminance < .179 else "black"),
                )

    fig.update_layout(
        title=title,
        height=540,
        yaxis=dict(autorange="reversed"),
    )
    plot(fig)


