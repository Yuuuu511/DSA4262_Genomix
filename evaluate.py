"""Evaluate frozen data0 models on data1 and document coordinate overlap."""
import argparse
import csv
import json
import platform
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

import joblib
import numpy as np
import sklearn
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support

from features import FEATURE_NAMES, FEATURE_VERSION, iter_sites
from train import digest, metrics, read_labels


def load_metadata(path):
    rows = {}
    with open(path, newline="") as handle:
        reader = csv.DictReader(handle)
        if not {"transcript_id", "transcript_position", "label"}.issubset(reader.fieldnames or []):
            raise ValueError("Metadata requires transcript_id, transcript_position, label")
        for row in reader:
            key = (row["transcript_id"], row["transcript_position"])
            if key in rows or float(row["label"]) not in (0, 1):
                raise ValueError(f"Duplicate site or non-binary label: {key}")
            rows[key] = row
    return rows


def summarise(y, score):
    result = {"sites": len(y), "positives": int(y.sum()),
              "positive_fraction": float(y.mean()) if len(y) else None}
    result["metrics"] = metrics(y, score) if len(np.unique(y)) == 2 else None
    if len(y):
        predicted = (score >= 0.5).astype(int)
        tn, fp, fn, tp = confusion_matrix(y, predicted, labels=[0, 1]).ravel()
        precision, recall, f1, _ = precision_recall_fscore_support(
            y, predicted, average="binary", zero_division=0)
        result["threshold_0_5"] = {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
                                     "precision": float(precision), "recall": float(recall), "f1": float(f1)}
    return result


def load_model(path):
    bundle = joblib.load(path)
    if bundle["feature_version"] != FEATURE_VERSION or bundle["feature_names"] != FEATURE_NAMES:
        raise ValueError("Model feature specification does not match")
    if bundle["sklearn_version"] != sklearn.__version__:
        raise ValueError("Use the same scikit-learn version as the saved model")
    return bundle


def write_document(report, path):
    all_sites = report["submission_model"]["all_data1"]
    overlap = report["overlap"]
    rows = []
    for name, group in report["submission_model"].items():
        m = group["metrics"]
        scores = [f"{m[k]:.6f}" for k in ("roc_auc", "average_precision", "pr_auc_trapezoidal", "log_loss", "brier_score")] if m else ["N/A"] * 5
        rows.append(f"| {name} | {group['sites']:,} | {group['positives']:,} | " + " | ".join(scores) + " |")
    safe = report["evaluation_model"]["original_heldout_genes_in_data1"]
    safe_metrics = safe["metrics"]
    rows.append(f"| evaluation model: original held-out genes | {safe['sites']:,} | {safe['positives']:,} | "
                + " | ".join(f"{safe_metrics[k]:.6f}" if safe_metrics else "N/A" for k in
                              ("roc_auc", "average_precision", "pr_auc_trapezoidal", "log_loss", "brier_score")) + " |")
    constant = report["constant_predictor"]
    cm = all_sites["threshold_0_5"]
    previous = report["previous_data0_heldout_metrics"]
    document = f"""# Frozen data0 baseline evaluated on data1

Evaluation date: {report['evaluated_at_singapore']}. Generated by `evaluate.py`.

## Outcome

The submission model trained on all 121,838 data0 sites was applied to every labelled data1 site without retraining, refitting the scaler, tuning, or selecting a threshold. The complete data1 evaluation contains **{all_sites['sites']:,} sites**, **{all_sites['positives']:,} positive labels** and **{all_sites['sites']-all_sites['positives']:,} negative labels** (positive prevalence: **{all_sites['positive_fraction']:.2%}**).

Its ROC AUC is **{all_sites['metrics']['roc_auc']:.6f}**, average precision is **{all_sites['metrics']['average_precision']:.6f}**, and trapezoidal PR AUC is **{all_sites['metrics']['pr_auc_trapezoidal']:.6f}**.

## Method

1. Load `models/data0_model.joblib`, including its data0-fitted scaler and logistic regression weights. Verify the feature specification and scikit-learn version.
2. Stream `data1/dataset1.json.gz` and calculate the same 45 label-free features used for data0: 18 signal summaries, log read count, and 26 sequence indicators. Neither label nor metadata offsets are model features.
3. Match each signal site to `data1/data.info` by `(transcript_id, transcript_position)`. Verify unique coordinates, complete signal/label matching, finite probabilities in [0, 1], and agreement between metadata read counts and observed signal read counts.
4. Predict in batches using the saved pipeline, then calculate ranking and probability-error metrics. Evaluate a constant predictor assigning the data0 positive fraction ({report['data0_positive_fraction']:.6f}) to each site.
5. Compare coordinates and transcript IDs against data0. Report the frozen submission model's performance on each subset below. No gene identities are inferred for transcripts missing from data0.
6. As an additional gene-separated check, apply `models/data0_evaluation_model.joblib` (trained on 98,006 sites from the original 80% gene split) to data1 sites whose transcripts map to original data0 held-out genes. These genes were absent from that model's training. This is a different model from the all-data0 submission model.

## Results

| Model / data1 subset | Sites | Positives | ROC AUC | Average precision | Trapezoidal PR AUC | Log loss | Brier score |
|---|---:|---:|---:|---:|---:|---:|---:|
{chr(10).join(rows)}

`overlapping_sites` means the same transcript and position occur in data0. `new_sites` means the coordinate pair does not occur in data0. `new_transcripts` means the transcript ID is absent from data0; this is a subset of `new_sites`, not an additional disjoint category.

For all data1 sites, the constant predictor's ROC AUC is **{constant['roc_auc']:.6f}** and average precision is **{constant['average_precision']:.6f}**. Its log loss is **{constant['log_loss']:.6f}** and Brier score is **{constant['brier_score']:.6f}**. The average-precision reference equals data1 prevalence. Trapezoidal PR AUC for a constant predictor is not a suitable prevalence reference because the curve's endpoint interpolation can inflate it.

For comparison, the original evaluation model's within-data0 gene-held-out ROC AUC was **{previous['roc_auc']:.6f}**, average precision **{previous['average_precision']:.6f}**, and trapezoidal PR AUC **{previous['pr_auc_trapezoidal']:.6f}**. This comparison involves different evaluation distributions and, for the full data1 row, a different training size. It should not be read as a controlled estimate of dataset shift.

## Overlap and independence

- **{overlap['sites']:,} / {all_sites['sites']:,} data1 sites ({overlap['fraction_of_data1']:.2%})** share transcript-position coordinates with data0.
- **{overlap['new_sites']:,} sites** have new coordinates. New coordinates can still belong to genes seen during training.
- **{overlap['transcripts']:,} transcript IDs** occur in both datasets; **{overlap['new_transcripts']:,} data1 transcript IDs** are absent from data0. Absence of a transcript ID does not establish absence of its gene; data1 has no gene-ID column, and no external annotation was used.
- Among shared coordinates, **{overlap['label_disagreements']:,} ({overlap['label_disagreement_fraction']:.2%})** have different binary labels. The files do not establish why: biological context, label generation, or other differences require source provenance. We use data1's labels as supplied and do not replace them with data0 labels.
- Label changes at shared coordinates: **{overlap['data0_0_data1_1']:,}** changed from 0 to 1; **{overlap['data0_1_data1_0']:,}** changed from 1 to 0.

The overall data1 score is a transfer check with substantial training-coordinate overlap, so it does not establish performance on entirely unseen genes or the hidden leaderboard. The new-transcript subset reduces transcript overlap but cannot prove gene separation. The additional evaluation-model row is separated from that model's training genes for all sites that can be mapped through data0 transcript annotations; it covers only that mapped subset. We have not verified cell-line identity, shared read molecules, or label-generation independence from the supplied files.

## Fixed 0.5 threshold diagnostic

At a probability threshold of 0.5, the full data1 evaluation gives TP **{cm['tp']:,}**, FP **{cm['fp']:,}**, FN **{cm['fn']:,}**, TN **{cm['tn']:,}**. Precision is **{cm['precision']:.6f}**, recall **{cm['recall']:.6f}**, and F1 **{cm['f1']:.6f}**. This threshold was not optimised and is not needed for leaderboard submission, which uses probability scores. ROC AUC measures ranking, not classification accuracy. Average precision and trapezoidal PR AUC use different integration conventions.

## Verification and reproducibility

All **{all_sites['sites']:,}** metadata sites matched unique signal records and predictions. No sites were dropped. Both model-file SHA-256 hashes remained unchanged across evaluation. Models were loaded and used only for prediction; no `.fit` calls were made. Historical versions, source hashes, subset counts and numeric metrics are published in `results/data1_evaluation/metrics.json`. New evaluations write `artifacts/data1/metrics.json` by default.

Run from the project directory with its virtual environment:

```bash
.venv/bin/python evaluate.py \\
  --data data/data1/dataset1.json.gz \\
  --labels data/data1/data.info \\
  --reference-labels data/data0/data.info.labelled
```

First run the data0 reproduction command in `docs/data0_training.md` to regenerate `artifacts/split.csv`. The defaults load the two packaged data0 models and `results/data0/metrics.json`; evaluation writes `artifacts/data1/` and this report. Historical result summaries are published in `results/data1_evaluation/`. Adjust input paths if your datasets are stored elsewhere.

| Output | Purpose |
|---|---|
| `artifacts/data1/predictions.csv` | All-data0 model probabilities, exactly three submission-format columns |
| `artifacts/data1/diagnostics.csv` | Both models' probabilities, labels, subset memberships, and known gene/split mapping |
| `artifacts/data1/metrics.json` | Full numeric evaluation, provenance and verification |
| `docs/data1_evaluation.md` | This human-readable report |

This evaluation provides a documented baseline check. It does not include model improvement, retraining with data1, or a leaderboard upload.
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(document)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True)
    parser.add_argument("--labels", required=True)
    parser.add_argument("--reference-labels", required=True)
    project = Path(__file__).resolve().parent
    parser.add_argument("--model", default=str(project / "models/data0_model.joblib"))
    parser.add_argument("--evaluation-model", default=str(project / "models/data0_evaluation_model.joblib"))
    parser.add_argument("--reference-metrics", default=str(project / "results/data0/metrics.json"))
    parser.add_argument("--split", default="artifacts/split.csv")
    parser.add_argument("--out", default="artifacts/data1")
    parser.add_argument("--report", default="docs/data1_evaluation.md")
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    inputs = {k: Path(v).resolve() for k, v in vars(args).items() if k in
              {"data", "labels", "reference_labels", "model", "evaluation_model", "split", "reference_metrics"}}
    before = {k: digest(v) for k, v in inputs.items()}
    bundle, evaluation_bundle = load_model(args.model), load_model(args.evaluation_model)
    reference = read_labels(args.reference_labels)
    if before["reference_labels"] != bundle["training_source"]["labels_sha256"]:
        raise ValueError("Reference labels do not match saved model training source")
    if bundle["training_source"] != evaluation_bundle["training_source"]:
        raise ValueError("Models do not share the same data0 source")
    gene_by_transcript = {}
    for (transcript, _), (gene, _) in reference.items():
        if transcript in gene_by_transcript and gene_by_transcript[transcript] != gene:
            raise ValueError("Inconsistent gene mapping")
        gene_by_transcript[transcript] = gene
    with open(args.split, newline="") as handle:
        split_rows = list(csv.DictReader(handle))
    if len(split_rows) != len(reference):
        raise ValueError("Split site count differs from data0")
    split_by_gene = {}
    split_keys = set()
    for r in split_rows:
        key = (r["transcript_id"], r["transcript_position"])
        if key in split_keys or reference[key] != (r["gene_id"], int(r["label"])):
            raise ValueError("Split does not match data0 labels")
        split_keys.add(key)
        gene, group = r["gene_id"], r["split"]
        if group not in {"train", "test"} or (gene in split_by_gene and split_by_gene[gene] != group):
            raise ValueError("Invalid gene split")
        split_by_gene[gene] = group
    if int(evaluation_bundle["pipeline"][0].n_samples_seen_) != sum(r["split"] == "train" for r in split_rows):
        raise ValueError("Evaluation model training size does not match split")
    if int(bundle["pipeline"][0].n_samples_seen_) != len(reference):
        raise ValueError("Submission model was not fitted on all reference sites")
    metadata = load_metadata(args.labels)
    keys, features, seen = [], [], set()
    for transcript, position, x in iter_sites(args.data):
        key = (transcript, position)
        if key in seen or key not in metadata:
            raise ValueError(f"Duplicate signal site or missing label: {key}")
        seen.add(key)
        if "n_reads" in metadata[key] and int(metadata[key]["n_reads"]) != round(np.expm1(x[18])):
            raise ValueError(f"Metadata read count mismatch: {key}")
        keys.append(key)
        features.append(x)
        if len(keys) % 20000 == 0:
            print(f"Extracted {len(keys):,} data1 sites", flush=True)
    if seen != set(metadata) or not keys:
        raise ValueError("Signals and metadata do not match completely")
    X = np.asarray(features)
    scores, evaluation_scores = [], []
    for start in range(0, len(X), 2048):
        scores.extend(bundle["pipeline"].predict_proba(X[start:start+2048])[:, 1])
        evaluation_scores.extend(evaluation_bundle["pipeline"].predict_proba(X[start:start+2048])[:, 1])
    score, evaluation_score = np.asarray(scores), np.asarray(evaluation_scores)
    for values in (score, evaluation_score):
        if not np.isfinite(values).all() or ((values < 0) | (values > 1)).any():
            raise ValueError("Invalid probabilities")
    y = np.asarray([int(float(metadata[k]["label"])) for k in keys], dtype=np.int8)
    overlapping = np.asarray([k in reference for k in keys])
    new_transcript = np.asarray([k[0] not in gene_by_transcript for k in keys])
    heldout_gene = np.asarray([split_by_gene.get(gene_by_transcript.get(k[0])) == "test" for k in keys])
    subsets = {"all_data1": np.ones(len(keys), dtype=bool), "overlapping_sites": overlapping,
               "new_sites": ~overlapping, "new_transcripts": new_transcript}
    transitions = {(a, b): sum(int(reference[k][1] == a and y[i] == b) for i, k in enumerate(keys) if overlapping[i])
                   for a, b in [(0, 1), (1, 0)]}
    n_overlap = int(overlapping.sum())
    n_disagree = sum(transitions.values())
    data0_prior = sum(v[1] for v in reference.values()) / len(reference)
    previous = json.loads(Path(args.reference_metrics).read_text())["heldout_metrics"]
    report = {"evaluated_at_singapore": datetime.now(ZoneInfo("Asia/Singapore")).isoformat(timespec="seconds"),
              "data0_positive_fraction": data0_prior,
              "submission_model": {name: summarise(y[mask], score[mask]) for name, mask in subsets.items()},
              "evaluation_model": {"original_heldout_genes_in_data1": summarise(y[heldout_gene], evaluation_score[heldout_gene])},
              "constant_predictor": metrics(y, np.full(len(y), data0_prior)),
              "previous_data0_heldout_metrics": previous,
              "overlap": {"sites": n_overlap, "fraction_of_data1": n_overlap / len(keys),
                          "new_sites": int((~overlapping).sum()),
                          "transcripts": len({k[0] for k in keys} & set(gene_by_transcript)),
                          "new_transcripts": len({k[0] for k in keys} - set(gene_by_transcript)),
                          "label_disagreements": n_disagree,
                          "label_disagreement_fraction": n_disagree / n_overlap if n_overlap else 0,
                          "data0_0_data1_1": transitions[(0, 1)], "data0_1_data1_0": transitions[(1, 0)]},
              "source": {k: {"path": str(inputs[k]), "sha256": before[k]} for k in inputs},
              "versions": {"python": platform.python_version(), "numpy": np.__version__,
                           "scikit_learn": sklearn.__version__, "joblib": joblib.__version__},
              "verification": {"metadata_sites": len(metadata), "signal_sites": len(keys),
                               "all_sites_matched": True, "probabilities_valid": True,
                               "both_model_files_unchanged": True, "data1_used_for_fitting": False}}
    for key in ("model", "evaluation_model"):
        if digest(inputs[key]) != before[key]:
            raise ValueError("Model file changed during evaluation")
    with (out / "predictions.csv").open("w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["transcript_id", "transcript_position", "score"])
        writer.writerows((t, p, float(s)) for (t, p), s in zip(keys, score))
    with (out / "diagnostics.csv").open("w", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["transcript_id", "transcript_position", "label", "score", "evaluation_model_score",
                         "overlaps_data0_site", "new_transcript", "known_gene_id", "original_gene_split"])
        for i, (t, p) in enumerate(keys):
            gene = gene_by_transcript.get(t, "")
            writer.writerow([t, p, int(y[i]), float(score[i]), float(evaluation_score[i]),
                             int(overlapping[i]), int(new_transcript[i]), gene, split_by_gene.get(gene, "unknown")])
    (out / "metrics.json").write_text(json.dumps(report, indent=2) + "\n")
    write_document(report, Path(args.report))
    print(json.dumps(report["submission_model"], indent=2), flush=True)
    print("Gene-separated evaluation-model subset:", json.dumps(report["evaluation_model"], indent=2), flush=True)
    print(f"Saved documentation to {Path(args.report).resolve()}", flush=True)


if __name__ == "__main__":
    main()
